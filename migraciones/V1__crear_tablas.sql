-- HatoControl · V1: tablas del diagrama entidad-relación (Fase 3).
-- Las reglas que dependen de la fecha de hoy (fechas no futuras) las valida el backend (RNF09).

CREATE TABLE fincas (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    fecha_registro  DATE         NOT NULL DEFAULT CURRENT_DATE
);

CREATE TABLE usuarios (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finca_id         BIGINT       NOT NULL REFERENCES fincas (id),
    nombre           VARCHAR(100) NOT NULL,
    correo           VARCHAR(254) NOT NULL,
    hash_contrasena  VARCHAR(100) NOT NULL,
    rol              VARCHAR(20)  NOT NULL,
    activo           BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_usuarios_correo UNIQUE (correo),
    CONSTRAINT ck_usuarios_rol CHECK (rol IN ('GANADERO', 'ADMINISTRADOR'))
);
CREATE INDEX ix_usuarios_finca ON usuarios (finca_id);

-- RNF23: solo se guarda el hash del token; vence y se usa una sola vez.
CREATE TABLE tokens_recuperacion (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT      NOT NULL REFERENCES usuarios (id),
    hash_token  VARCHAR(100) NOT NULL,
    vence_en    TIMESTAMP   NOT NULL,
    usado       BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_tokens_hash UNIQUE (hash_token)
);
CREATE INDEX ix_tokens_usuario ON tokens_recuperacion (usuario_id);

CREATE TABLE animales (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finca_id          BIGINT      NOT NULL REFERENCES fincas (id),
    codigo_arete      VARCHAR(30) NOT NULL,
    nombre            VARCHAR(100),
    sexo              VARCHAR(10) NOT NULL,
    fecha_nacimiento  DATE,
    proposito         VARCHAR(10) NOT NULL,
    parto_id          BIGINT,
    -- RN01: el arete es único dentro de la finca
    CONSTRAINT uq_animales_finca_arete UNIQUE (finca_id, codigo_arete),
    CONSTRAINT ck_animales_sexo CHECK (sexo IN ('MACHO', 'HEMBRA')),
    CONSTRAINT ck_animales_proposito CHECK (proposito IN ('ENGORDE', 'PADRON', 'LECHE')),
    -- padrón solo para machos; leche solo para hembras
    CONSTRAINT ck_animales_proposito_sexo CHECK (
        (proposito <> 'PADRON' OR sexo = 'MACHO') AND (proposito <> 'LECHE' OR sexo = 'HEMBRA'))
);

CREATE TABLE partos (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    madre_id  BIGINT NOT NULL REFERENCES animales (id),
    fecha     DATE   NOT NULL
);
CREATE INDEX ix_partos_madre ON partos (madre_id);

-- Un animal puede haber nacido en un parto registrado en la finca (relación «nacen en»).
ALTER TABLE animales
    ADD CONSTRAINT fk_animales_parto FOREIGN KEY (parto_id) REFERENCES partos (id);
CREATE INDEX ix_animales_parto ON animales (parto_id);

CREATE TABLE registros_sanitarios (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id          BIGINT       NOT NULL REFERENCES animales (id),
    tipo               VARCHAR(15)  NOT NULL,
    descripcion        VARCHAR(200) NOT NULL,
    fecha_programada   DATE,
    fecha_realizacion  DATE,
    estado             VARCHAR(15)  NOT NULL,
    observaciones      TEXT,
    CONSTRAINT ck_sanitarios_tipo CHECK (tipo IN ('VACUNA', 'ENFERMEDAD', 'TRATAMIENTO')),
    CONSTRAINT ck_sanitarios_estado CHECK (estado IN ('PROGRAMADA', 'REALIZADA')),
    -- programada necesita fecha programada; realizada necesita fecha de realización
    CONSTRAINT ck_sanitarios_fechas CHECK (
        (estado = 'PROGRAMADA' AND fecha_programada IS NOT NULL AND fecha_realizacion IS NULL)
        OR (estado = 'REALIZADA' AND fecha_realizacion IS NOT NULL))
);
CREATE INDEX ix_sanitarios_animal ON registros_sanitarios (animal_id);
CREATE INDEX ix_sanitarios_programadas ON registros_sanitarios (fecha_programada) WHERE estado = 'PROGRAMADA';

CREATE TABLE registros_peso (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id       BIGINT           NOT NULL REFERENCES animales (id),
    peso_kg         DOUBLE PRECISION NOT NULL,
    fecha_medicion  DATE             NOT NULL,
    CONSTRAINT ck_peso_positivo CHECK (peso_kg > 0)
);
CREATE INDEX ix_peso_animal_fecha ON registros_peso (animal_id, fecha_medicion);

CREATE TABLE registros_leche (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_id  BIGINT           NOT NULL REFERENCES animales (id),
    parto_id   BIGINT           NOT NULL REFERENCES partos (id),
    fecha      DATE             NOT NULL,
    litros     DOUBLE PRECISION NOT NULL,
    -- un solo registro de leche por vaca y día
    CONSTRAINT uq_leche_animal_fecha UNIQUE (animal_id, fecha),
    CONSTRAINT ck_leche_positiva CHECK (litros > 0)
);
CREATE INDEX ix_leche_parto ON registros_leche (parto_id);
